# После каждых TREND_EVERY мотивационных постов выходит один пост про изделие для 3D-печати.
TREND_EVERY = 2


def mix_posts(main, extra, every):
    """Вставляет по одному посту из extra после каждых `every` постов из main."""
    result = []
    extra_iter = iter(extra)
    for i, post in enumerate(main, start=1):
        result.append(post)
        if i % every == 0:
            nxt = next(extra_iter, None)
            if nxt is not None:
                result.append(nxt)
    result.extend(extra_iter)
    return result


POSTS = mix_posts(MOTIVATION_POSTS, TREND_POSTS, TREND_EVERY)

STATE_FILE = "state.json"
MAX_USED_PHOTOS = 60   # столько последних картинок помним, чтобы не повторять
PEXELS_URL = "https://api.pexels.com/v1/search"
FALLBACK_QUERY = "3d printer"   # запасной запрос, если по теме поста ничего не нашлось


def within_posting_window():
    """True, если сейчас по местному времени (UTC+7) от 9:00 до 22:00.
    При ручном запуске (кнопка Run workflow) проверка времени пропускается,
    чтобы можно было проверить работу в любое время."""
    if os.environ.get("GITHUB_EVENT_NAME") == "workflow_dispatch":
        return True
    now = datetime.now(LOCAL_TZ)
    print(f"Местное время (UTC+7): {now.strftime('%H:%M')}")
    return START_HOUR <= now.hour < END_HOUR


def load_state():
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return {}


def save_state(state):
    with open(STATE_FILE, "w", encoding="utf-8") as f:
        json.dump(state, f, ensure_ascii=False)


def download_url(url, attempts=3):
    """Скачивает файл по ссылке с повторными попытками. Возвращает bytes или None."""
    for i in range(1, attempts + 1):
        print(f"Попытка {i}/{attempts}: загрузка {url}")
        try:
            r = requests.get(url, timeout=20)
            if r.status_code == 200 and r.content:
                return r.content
            print(f"Статус {r.status_code}")
        except requests.RequestException as e:
            print(f"Ошибка {e}")
        if i < attempts:
            time.sleep(2 * i)
    return None


def download_random_image():
    """Случайная картинка для мотивационных постов.
    Каждый запуск берёт новый seed, поэтому картинка не повторяется."""
    seed = time.time_ns()
    return download_url(f"https://picsum.photos/seed/{seed}/1000/600")


def find_pexels_photo(query, used_ids, api_key):
    """Ищет на Pexels фото по теме. Возвращает словарь фото или None."""
    try:
        r = requests.get(
            PEXELS_URL,
            headers={"Authorization": api_key},
            params={"query": query, "per_page": 15, "orientation": "landscape"},
            timeout=20,
        )
        if r.status_code != 200:
            print(f"Pexels: статус {r.status_code}")
            return None
        photos = r.json().get("photos", [])
    except (requests.RequestException, ValueError) as e:
        print(f"Pexels: ошибка {e}")
        return None
    if not photos:
        print(f"Pexels: по запросу «{query}» ничего не найдено")
        return None
    fresh = [p for p in photos if p.get("id") not in used_ids]
    return random.choice(fresh or photos)


def get_topic_image(query, used_ids):
    """Картинка по теме поста. Возвращает (bytes, id фото) или (None, None)."""
    api_key = os.environ.get("PEXELS_API_KEY")
    if not api_key:
        print("WARNING: PEXELS_API_KEY не задан, картинку по теме подобрать нельзя")
        return None, None
    queries = [query] if query == FALLBACK_QUERY else [query, FALLBACK_QUERY]
    for q in queries:
        photo = find_pexels_photo(q, used_ids, api_key)
        if not photo:
            continue
        src = photo.get("src", {})
        img_url = src.get("large") or src.get("original")
        data = download_url(img_url) if img_url else None
        if data:
            return data, photo.get("id")
    return None, None


def main():
    if not within_posting_window():
        print(f"Вне времени публикации ({START_HOUR}:00-{END_HOUR - 1}:59 по UTC+7). Пост пропущен.")
        return

    token = os.environ.get("TELEGRAM_TOKEN")
    chat_id = os.environ.get("TELEGRAM_TO")

    if not token or not chat_id:
        print("ERROR: TELEGRAM_TOKEN or TELEGRAM_TO is not set!")
        exit(1)

    state = load_state()
    index = state.get("index", 0)
    if not isinstance(index, int) or index >= len(POSTS):
        index = 0
    used_photos = state.get("used_photos", [])

    post = POSTS[index]

    photo_id = None
    if post.get("image_query"):
        image, photo_id = get_topic_image(post["image_query"], used_photos)
    else:
        image = download_random_image()

    if image:
        url = f"https://api.telegram.org/bot{token}/sendPhoto"
        files = {"photo": ("image.jpg", image, "image/jpeg")}
        data = {"chat_id": chat_id, "caption": post["caption"]}
        response = requests.post(url, data=data, files=files, timeout=30)
        mode = "with photo"
    else:
        print("WARNING: image unavailable, sending text only")
        url = f"https://api.telegram.org/bot{token}/sendMessage"
        data = {"chat_id": chat_id, "text": post["caption"]}
        response = requests.post(url, data=data, timeout=30)
        mode = "text only"

    res_data = response.json()

    print("Telegram Response:", res_data)
    if not res_data.get("ok"):
        print("ERROR: Telegram API rejected the post!")
        exit(1)

    next_index = (index + 1) % len(POSTS)
    state["index"] = next_index
    if photo_id is not None:
        used_photos.append(photo_id)
    state["used_photos"] = used_photos[-MAX_USED_PHOTOS:]
    save_state(state)
    print(f"Successfully published post index {index} ({mode}). Next index will be {next_index}.")


if __name__ == "__main__":
    main()
