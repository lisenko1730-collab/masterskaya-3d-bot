def load_state() -> dict:
    if not STATE_FILE.exists():
        return {"next_index": 0}
    try:
        return json.loads(STATE_FILE.read_text(encoding="utf-8"))
    except Exception:
        return {"next_index": 0}


def save_state(state: dict) -> None:
    STATE_FILE.write_text(json.dumps(state, indent=2), encoding="utf-8")


def download_image(url: str) -> bytes:
    last_err = None
    for attempt in range(3):
        try:
            r = requests.get(url, headers={"User-Agent": "Mozilla/5.0"}, timeout=20)
            r.raise_for_status()
            if not r.content:
                raise RuntimeError("empty image body")
            return r.content
        except Exception as e:
            last_err = e
            print(f"Download attempt {attempt + 1}/3 failed: {e}")
            if attempt < 2:
                time.sleep(2 ** attempt)
    raise RuntimeError(f"Failed to download image: {last_err}")


def send_photo(image_bytes: bytes, caption: str) -> None:
    resp = requests.post(
        f"https://api.telegram.org/bot{token}/sendPhoto",
        data={"chat_id": chat_id, "caption": caption},
        files={"photo": ("image.jpg", image_bytes, "image/jpeg")},
        timeout=30,
    )
    print("Telegram HTTP:", resp.status_code)
    data = resp.json()
    print("Telegram response:", data)
    if not data.get("ok"):
        raise RuntimeError("Telegram API returned ok=false")


def main() -> None:
    state = load_state()
    index = int(state.get("next_index", 0)) % len(POSTS)

    url, caption = POSTS[index]
    print(f"Publishing post {index + 1}/{len(POSTS)}")
    print(f"Image: {url}")

    image_bytes = download_image(url)
    send_photo(image_bytes, caption)

    state["next_index"] = (index + 1) % len(POSTS)
    save_state(state)
    print(f"Done. next_index={state['next_index']}")


if __name__ == "__main__":
    main()
